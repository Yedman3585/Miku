def miku(tail, torso, legs, tail_dy=2, head_dy=0):
    """Собирает кадр Miku 21x22 (ноги всегда у нижнего края)."""
    return compose([
        (tail, 0, tail_dy + head_dy),
        (HEAD, HEAD_X, head_dy),
        (torso, 11, 10 + head_dy),
        (LEGS[legs], 11, 16 + head_dy),
    ], SPR_W_PX, SPR_H_PX)


