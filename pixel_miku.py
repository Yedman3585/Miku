def to_mask(rows):
    h, w = len(rows), max(len(r) for r in rows)
    m = np.zeros((h, w), dtype=bool)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == "#" or (c == "+" and (x + y) % 2 == 0):
                m[y, x] = True
    return m


def compose(parts, w, h):
    """parts: [(rows, x, y)] -> bool[h,w]; '.' ничего не стирает."""
    m = np.zeros((h, w), dtype=bool)
    for rows, ox, oy in parts:
        pm = to_mask(rows)
        ph, pw = pm.shape
        m[oy:oy + ph, ox:ox + pw] |= pm
    return m


SPR_W_PX, SPR_H_PX = 21, 22
